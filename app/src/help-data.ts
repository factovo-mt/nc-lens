/** CHANGELOG.md の「## 版 - 日付」と箇条書き */
export function history(): { version: string; date: string; items: string[] }[] {
  const out: { version: string; date: string; items: string[] }[] = [];
  for (const line of changelog.split(/\r?\n/)) {
    const h = /^##\s+(\S+)(?:\s+-\s+(\S+))?/.exec(line);
    if (h) out.push({ version: h[1], date: h[2] ?? "", items: [] });
    else if (out.length && /^-\s+/.test(line)) out[out.length - 1].items.push(line.replace(/^-\s+/, ""));
    else if (out.length && line.trim() && !out[out.length - 1].items.length) out[out.length - 1].items.push(line.trim());
  }
  return out;
}
