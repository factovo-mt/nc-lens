#Requires -Version 7.0
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$tools = Join-Path $root 'scratch/release-tools'
$scanner = Join-Path $tools 'bin/cargo-license.exe'
$target = 'x86_64-pc-windows-msvc'

Push-Location $root
try {
    if (-not (Test-Path -LiteralPath $scanner)) {
        cargo install cargo-license --version 0.7.0 --locked --root $tools
        if ($LASTEXITCODE -ne 0) { throw 'cargo-license installation failed.' }
    }
    $metadata = cargo metadata --locked --format-version 1 --filter-platform $target | ConvertFrom-Json -Depth 50
    if ($LASTEXITCODE -ne 0) { throw 'cargo metadata failed.' }
    $rust = & $scanner --json --filter-platform $target | ConvertFrom-Json
    if ($LASTEXITCODE -ne 0) { throw 'cargo-license failed.' }

    Push-Location app
    try {
        pnpm install --frozen-lockfile | Out-Host
        if ($LASTEXITCODE -ne 0) { throw 'pnpm install failed.' }
        $npm = pnpm licenses list --json | ConvertFrom-Json -AsHashtable
        if ($LASTEXITCODE -ne 0) { throw 'pnpm licenses list failed.' }
    } finally {
        Pop-Location
    }
    if (-not $rust -or -not $npm) { throw 'Dependency license list is empty.' }

    $report = [System.Collections.Generic.List[string]]::new()
    $report.AddRange([string[]]@(
        '# Third-party licenses', '',
        'Generated by scripts/gen-licenses.ps1.',
        'Scope: Windows x64 Rust workspace dependency resolution and installed pnpm dependencies, including development and build tooling.',
        'A listed package is not necessarily linked into the distributed application.',
        'For Rust source, follow each versioned crates.io link and select Download. For npm source, follow the package link and choose the listed version.',
        'MPL-2.0 source is available under the Mozilla Public License 2.0 from the linked packages.', '',
        '## Rust', '', '| Package | Version | Declared license |', '| --- | --- | --- |'
    ))
    $directories = @{}
    $missing = [System.Collections.Generic.List[string]]::new()
    foreach ($record in ($rust | Sort-Object name, version)) {
        $resolved = $metadata.packages | Where-Object {
            $_.name -ceq $record.name -and $_.version -eq $record.version -and $_.source
        }
        if (-not $resolved) { continue }
        $label = "$($record.name) $($record.version)"
        $url = "https://crates.io/crates/$($record.name)/$($record.version)"
        $report.Add("| [$($record.name)]($url) | $($record.version) | $($record.license ?? 'UNKNOWN') |")
        $directories["Rust: $label"] = @($resolved | ForEach-Object { Split-Path -Parent $_.manifest_path })
        foreach ($crate in $resolved) {
            if ($crate.license_file) {
                $directories["Rust: $label"] += Join-Path (Split-Path -Parent $crate.manifest_path) $crate.license_file
            }
        }
    }

    $report.AddRange([string[]]@('', '## npm', '', '| Package | Version | Declared license |', '| --- | --- | --- |'))
    foreach ($record in ($npm.Values | ForEach-Object { $_ } | Sort-Object name, license)) {
        $url = "https://www.npmjs.com/package/$($record.name)"
        $versions = $record.versions -join ', '
        $report.Add("| [$($record.name)]($url) | $versions | $($record.license ?? 'UNKNOWN') |")
        $directories["npm: $($record.name) $versions"] = $record.paths
    }

    $notices = @{}
    foreach ($label in ($directories.Keys | Sort-Object)) {
        $files = @(
            foreach ($path in $directories[$label]) {
                if (Test-Path -LiteralPath $path -PathType Leaf) {
                    Get-Item -LiteralPath $path
                } else {
                    Get-ChildItem -LiteralPath $path -File | Where-Object Name -Match '^(licen[sc]e|copying|notice|copyright|unlicense)([._-]|$)'
                }
            }
        )
        if (-not $files) { $missing.Add($label) }
        foreach ($file in ($files | Sort-Object FullName -Unique)) {
            $hash = (Get-FileHash -LiteralPath $file.FullName -Algorithm SHA256).Hash
            if (-not $notices.ContainsKey($hash)) {
                $notices[$hash] = @{
                    Text = Get-Content -LiteralPath $file.FullName -Raw -Encoding UTF8
                    Labels = [System.Collections.Generic.List[string]]::new()
                }
            }
            $notices[$hash].Labels.Add("$label ($($file.Name))")
        }
    }
    $report.AddRange([string[]]@('', '## Packages without a separate notice file', '',
        'See the package sources above for notices in source files or README files.', ''))
    foreach ($label in $missing) { $report.Add("- $label") }
    $report.AddRange([string[]]@('', '## License and notice files', ''))
    foreach ($notice in ($notices.Values | Sort-Object { $_.Labels[0] })) {
        $report.Add("### $($notice.Labels -join '; ')")
        $report.Add('')
        foreach ($line in ($notice.Text -split '\r?\n')) { $report.Add("    $line".TrimEnd()) }
        $report.Add('')
    }
    $report | Set-Content -LiteralPath (Join-Path $root 'THIRD_PARTY_LICENSES.md') -Encoding UTF8
} finally {
    Pop-Location
}
